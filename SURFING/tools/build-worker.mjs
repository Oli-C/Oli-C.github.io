#!/usr/bin/env node
/* Builds tools/surf-worker.js, the one file pasted into the Cloudflare
   worker, from the site's own spots.js and score.js plus tools/worker/*.
   Workers can't load code at run time, so the shared scoring code is
   bundled in; that's what keeps the hourly blend identical to the pages'.

     node SURFING/tools/build-worker.mjs           write the bundle
     node SURFING/tools/build-worker.mjs --check   fail if it's out of date

   The bundle carries a short hash of its sources (WORKER_BUILD), which
   GET /health reports, so you can tell whether the deployed one is current. */
import fs from 'node:fs';
import crypto from 'node:crypto';

const at = (p) => new URL(p, import.meta.url);
const parts = [
  ['spots.js', '../spots.js'],
  ['score.js', '../score.js'],
  ['worker/feedback.js', './worker/feedback.js'],
  ['worker/forecast.js', './worker/forecast.js'],
  ['worker/main.js', './worker/main.js'],
];
const sources = parts.map(([name, p]) => [name, fs.readFileSync(at(p), 'utf8').replace(/\r\n/g, '\n')]);
const hash = crypto.createHash('sha256').update(sources.map(([, s]) => s).join('\n')).digest('hex').slice(0, 10);
const out = [
  `/* GENERATED by SURFING/tools/build-worker.mjs — don't edit; edit the sources and rebuild.`,
  `   Paste this whole file into the Cloudflare worker (Edit code → Deploy).`,
  `   Bindings: KV namespace FEEDBACK; EXPORT_KEY (secret or Secrets Store).`,
  `   Triggers: a Cron Trigger every hour, e.g. "5 * * * *".`,
  `   Build ${hash}. */`,
  `const WORKER_BUILD = '${hash}';`,
  ...sources.map(([name, s]) => `\n/* ===== ${name} ===== */\n${s.trim()}\n`),
].join('\n');

const target = at('./surf-worker.js');
const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
if (process.argv.includes('--check')) {
  if (current !== out) { console.error(`surf-worker.js is out of date (sources are build ${hash}); run node SURFING/tools/build-worker.mjs`); process.exit(1); }
  console.log(`surf-worker.js is current (build ${hash})`);
} else {
  fs.writeFileSync(target, out);
  console.log(`wrote SURFING/tools/surf-worker.js (build ${hash}, ${(out.length / 1024).toFixed(0)} KB)`);
}
